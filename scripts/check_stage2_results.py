"""Check the literal S2 synthetic reference without generating expected answers."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sqlite3
import sys
from urllib.parse import quote

from bbag.jsonio import read_json_object
from bbag.provenance import json_bytes
from bbag.s1_contracts import MarketPanel, Observation, Session
from bbag.s2_contracts import S2Config, S2RunManifest, S2SyntheticResult, canonical_s2_config, load_s2_config
from bbag.s2_data import DailyBar, action_entitlement
from bbag.s2_tasks import TaskResponse


def require(value: bool, message: str) -> None:
    if not value:
        raise ValueError(message)


def check_fixed_rows(config: S2Config, result: S2SyntheticResult, expected: dict,
                     raw_source: dict, expected_bars: list[DailyBar]) -> str:
    """Independent fixed-example oracle, not a second call to the data service.

    All eight fixture bars are known and complete at their four signal times.
    The literal asset ordering/jump answers remain in s2_expected.json. The two
    known action keys below are hand-listed from this synthetic example; none of
    these expected verdicts are generated by data_quality/historical_universe.
    """
    require(config.bundle is not None, "fixed reference requires its synthetic bundle")
    sessions = config.bundle.sessions
    require(result.universe.data_id == result.quality.data_id == config.bundle.data_id
            and result.universe.as_of == result.quality.as_of == config.request.as_of,
            "fixed universe/quality reference data or as_of differs")
    require(len(result.universe.rows) == len(sessions) == len(expected["universe_assets"]),
            "fixed universe reference session count differs")
    for row, session, assets in zip(result.universe.rows, sessions, expected["universe_assets"]):
        # Typed aware datetimes compare instants, accepting equivalent offsets.
        require(row.session == session.session and row.signal_at == session.signal_at,
                "fixed universe reference session or signal_at differs")
        require(row.assets == assets, "lagged hand-calculated universe differs")

    keys = [(session.session.isoformat(), sid) for session in sessions for sid in sorted(config.request.assets)]
    actual_keys = [(row.session.isoformat(), row.sid) for row in result.quality.rows]
    require(actual_keys == keys and len(actual_keys) == len(set(actual_keys)),
            "fixed quality reference keys must be complete, unique and ordered")
    known_actions = {("2024-01-04", "SYN_A"), ("2024-01-05", "SYN_B")}
    jump_keys = {tuple(item) for item in expected["raw_close_jumps"]}
    for row, key in zip(result.quality.rows, keys):
        reference = dict(session=key[0], sid=key[1], present=True, available=True,
                         missing_fields=[], stale=False, zero_volume=False,
                         raw_close_jump=key in jump_keys, known_action_on_session=key in known_actions)
        require(row.model_dump(mode="json") == reference,
                "fixed quality reference row differs: " + "/".join(key))
    quality = result.quality
    available = sum(row.available for row in quality.rows)
    complete = sum(row.available and not row.missing_fields for row in quality.rows)
    require(quality.expected_bars == len(quality.rows) and quality.available_bars == available
            and quality.complete_bars == complete
            and quality.coverage == (complete / len(quality.rows) if quality.rows else 0.0),
            "quality summaries do not match their actual row verdicts")
    for key in ("expected_bars", "available_bars", "complete_bars", "coverage"):
        require(getattr(quality, key) == expected[key], "literal quality reference differs: " + key)

    # Independently map the separately hashed raw input to the accepted typed S1
    # schema. Do not ask to_s1_panel to generate its own expected digest. This
    # fixed example has all request fields, sessions and bars; no field values,
    # availability times or normalization adjustments are manufactured here.
    panel = MarketPanel(data_id=config.bundle.data_id, source="synthetic_fixture", timezone=config.bundle.timezone,
        sessions=[Session.model_validate_json(json.dumps(item)) for item in raw_source["sessions"]],
        assets=sorted(config.request.assets), fields=list(config.request.fields),
        observations=[Observation(session=bar.session, asset=bar.sid, available_at=bar.available_at,
            values={field: getattr(bar, field) for field in config.request.fields})
            for bar in sorted(expected_bars, key=lambda item: (item.session, item.sid))])
    projection_hash = hashlib.sha256(json_bytes(panel.model_dump(mode="json"))).hexdigest()
    require(result.projected_s1_panel_sha256 == projection_hash,
            "fixed projection reference SHA-256 differs from the raw fixture mapped to S1")
    return projection_hash


def check_results(run: Path, root: Path | None = None) -> dict:
    root = root or Path(__file__).resolve().parents[1]
    expected = read_json_object(root / "tests/fixtures/s2_expected.json")
    raw_path = root / "tests/fixtures/s2_raw.json"
    raw_source = read_json_object(raw_path)
    config = load_s2_config(run / "config.json")
    require(config.request.provider == "SYNTHETIC", "the reference checker accepts synthetic data only")
    require(canonical_s2_config(config) == canonical_s2_config(load_s2_config(root / "configs/s2.example.json")),
            "run configuration differs from the committed synthetic example")
    record = S2RunManifest.model_validate_json(json.dumps(read_json_object(run / "run.json")))
    content = (run / "result.json").read_bytes()
    result = S2SyntheticResult.model_validate_json(json.dumps(read_json_object(run / "result.json")))
    require(record.config_sha256 == result.config_sha256 == hashlib.sha256(canonical_s2_config(config)).hexdigest(), "configuration hash mismatch")
    require(record.result_sha256 == hashlib.sha256(content).hexdigest(), "result bytes hash mismatch")
    require(config.bundle is not None and config.bundle.provenance.source_sha256 == hashlib.sha256(raw_path.read_bytes()).hexdigest(), "raw fixture source hash mismatch")
    # ISO Z and +00:00 represent the same instant; compare typed bars without
    # rewriting the separately hashed original raw bytes or any price answer.
    expected_bars = [DailyBar.model_validate_json(json.dumps(item)) for item in raw_source["bars"]]
    require(config.bundle.bars == expected_bars, "raw fields were not preserved")
    projection_hash = check_fixed_rows(config, result, expected, raw_source, expected_bars)
    jumps = [[row.session.isoformat(), row.sid] for row in result.quality.rows if row.raw_close_jump]
    require(jumps == expected["raw_close_jumps"], "raw split jump context differs")
    for action in config.bundle.corporate_actions:
        actual = action_entitlement(action, 10.0, as_of=config.request.as_of).model_dump(mode="json")
        key = "split_entitlement_for_10_shares" if action.kind == "SPLIT" else "dividend_entitlement_for_10_shares"
        require(actual == expected[key], "independent action entitlement differs")
    require(result.task.spec.response_class == expected["local_task_class"], "fixture must not impersonate platform evidence")
    require(result.task.spec.source_commit == record.code_commit, "task source differs from run source")
    require(result.usage.attempt_count == expected["local_task_attempt_count"] and len(result.task.attempts) == 1, "fixture attempt accounting differs")
    require([a.platform_task_id for a in result.task.attempts if a.platform_task_id is not None] == expected["provider_task_ids"], "fixture invented provider IDs")
    for attempt in result.task.attempts:
        for reference in attempt.raw_metadata:
            path = run / "metadata" / reference.relative_path
            payload = path.read_bytes()
            require(len(payload) == reference.size_bytes and hashlib.sha256(payload).hexdigest() == reference.sha256, "persisted metadata bytes mismatch")
            metadata = TaskResponse.model_validate_json(json.dumps(read_json_object(path)))
            require(metadata.response_class == "SYNTHETIC_TEST" and metadata.source_commit == record.code_commit, "metadata source/class mismatch")
    database = run / "task_ledger.sqlite"
    connection = sqlite3.connect("file:" + quote(database.resolve().as_posix(), safe="/:") + "?mode=ro&immutable=1", uri=True)
    try:
        require(connection.execute("PRAGMA integrity_check").fetchone()[0] == "ok", "SQLite integrity check failed")
        require(not connection.execute("PRAGMA foreign_key_check").fetchall(), "SQLite foreign-key check failed")
    finally:
        connection.close()
    return {"reference_passed": True, "provider": "SYNTHETIC", "universe_rows": len(result.universe.rows),
            "quality_rows": len(result.quality.rows), "local_task_attempts": result.usage.attempt_count,
            "projected_s1_panel_sha256": projection_hash,
            "platform_execution": "NOT_RUN", "independent_review": "PENDING"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(check_results(args.run), ensure_ascii=False))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, KeyError, TypeError, ArithmeticError, sqlite3.Error) as exc:
        print(json.dumps({"stage": "S2", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        raise SystemExit(2)
